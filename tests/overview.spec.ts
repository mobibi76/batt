import { test, expect } from '@playwright/test';

test('quality-first overview updates queues, traceability and latest-result defects', async ({ page }) => {
  await page.goto('/batt/');
  await page.getByRole('button', { name: '샘플 데이터로 체험하기' }).click();
  const overview = async () => page.getByRole('navigation').getByRole('button', { name: '운영 현황', exact: true }).click();
  const outcomes = page.locator('.outcome-card');
  await expect(outcomes.locator('h2')).toHaveText(['최종검사 불량률', '검사 이력 연결률']);
  await expect(outcomes.locator('.outcome-value')).toHaveText(['—', '—']);
  const sections = await page.locator('.quality-priorities, .work-queues, .process-panel, .throughput-panel').evaluateAll(es => es.map(e => e.className));
  expect(sections).toEqual(['quality-priorities', 'panel work-queues', 'panel process-panel', 'panel throughput-panel']);
  await page.getByRole('button', { name: '셀 매칭 시작' }).click();
  await page.getByRole('button', { name: '조합 추천', exact: true }).click();
  await page.getByRole('button', { name: '조합 검토 · 확정' }).first().click();
  await page.getByRole('textbox', { name: '팩 일련번호' }).fill('QUALITY-OVERVIEW');
  await page.getByRole('button', { name: '확인 및 팩 구성', exact: true }).click();
  await overview();
  await expect(page.locator('.queue-value')).toHaveText(['2조합', '1팩', '0팩']);
  await expect(outcomes.locator('.outcome-value')).toHaveText(['—', '0%']);
  await page.getByRole('button', { name: /에이징 기록 대기/ }).click();
  await page.getByRole('button', { name: '상세 조회' }).click();
  await page.getByRole('button', { name: '검사 결과 저장' }).click();
  await page.getByRole('button', { name: '닫기', exact: true }).click();
  await overview();
  await expect(page.locator('.queue-value')).toHaveText(['2조합', '0팩', '1팩']);
  await page.getByRole('button', { name: /최종검사 기록 대기/ }).click();
  await page.getByRole('button', { name: '상세 조회' }).click();
  await page.getByLabel('검사 구분').selectOption('final');
  await page.getByLabel('판정').selectOption('fail');
  await page.getByRole('button', { name: '검사 결과 저장' }).click();
  await page.getByRole('button', { name: '닫기', exact: true }).click();
  await overview();
  await expect(outcomes.locator('.outcome-value')).toHaveText(['100%', '100%']);
  await expect(page.locator('.queue-value')).toHaveText(['2조합', '0팩', '0팩']);
  await expect(page.locator('.queue-note')).toContainText('불합격 1팩');
  await page.getByRole('button', { name: '검사 결과 확인', exact: true }).click();
  await page.getByRole('button', { name: '상세 조회' }).click();
  await page.getByLabel('검사 구분').selectOption('final');
  await page.getByLabel('판정').selectOption('pass');
  await page.getByRole('button', { name: '검사 결과 저장' }).click();
  await page.getByRole('button', { name: '닫기', exact: true }).click();
  await overview();
  await expect(outcomes.locator('.outcome-value')).toHaveText(['0%', '100%']);
  await expect(page.locator('.queue-note')).toContainText('불합격 0팩');
  await expect(page.locator('.throughput-grid')).toContainText('최종검사 기록 팩1팩');
});
